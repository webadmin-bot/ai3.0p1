/**
 * Authoritative Universal Export Serializer
 * Generates completely synchronized, honest, and objective exports:
 * 1. Production Bible Markdown
 * 2. Google Flow Manifest JSON
 * 3. Cinematic Shot List CSV
 * 4. Full Studio Project Backup JSON
 *
 * Guarantees 100% consistency in story title, timing, assigned dialogue,
 * routing modes, reference checklists, media readiness, and audit summaries.
 */

import { Project, ScriptScene, CinematicShot, GoogleFlowShotPackage } from '../types/filmStudio';
import { extractExactSpeechForShot } from './flowPromptPackageEngine';

export interface AuthoritativeExportPackage {
  productionBibleMarkdown: string;
  flowManifestJson: string;
  shotListCsv: string;
  projectBackupJson: string;
  auditSummary: {
    totalPlannedRuntime: number;
    targetRuntime: number;
    runtimeDiscrepancySeconds: number;
    totalShots: number;
    totalScenes: number;
    ingredientsShotsCount: number;
    framesShotsCount: number;
    speechLinesCount: number;
    missingSpeechCount: number;
    missingMediaCount: number;
    isSourceStale: boolean;
    issues: string[];
  };
}

/**
 * Compiles universal audit metrics across the project
 */
export function compileUniversalAuditReport(project: Project) {
  const shots: CinematicShot[] = project.stage3?.shots || [];
  const scenes: ScriptScene[] = project.stage3?.scenes || [];
  const packages: GoogleFlowShotPackage[] = project.stage4?.shotPackages || [];
  const settings = project.settings;

  const totalPlannedRuntime = shots.reduce((acc, s) => acc + (s.duration || 8), 0);
  const targetRuntime = settings?.targetRuntimeSeconds || 60;
  const runtimeDiscrepancySeconds = Math.abs(totalPlannedRuntime - targetRuntime);

  const ingredientsShotsCount = shots.filter((s) => s.flowMode === 'INGREDIENTS').length;
  const framesShotsCount = shots.filter((s) => s.flowMode === 'FRAMES').length;

  // Speech audit
  let totalAssignedSpeechLines = 0;
  let unmappedSpeechLines = 0;

  scenes.forEach((sc) => {
    (sc.dialogueBlocks || []).forEach((block) => {
      totalAssignedSpeechLines++;
      const isAssigned = shots.some(
        (sh) =>
          (sh.dialogueRefs || []).includes(block.id) ||
          (sh.dialogueText && sh.dialogueText.includes(block.dialogue))
      );
      if (!isAssigned) {
        unmappedSpeechLines++;
      }
    });
  });

  // Media readiness audit
  const missingMediaCount = packages.filter(
    (p) => p.mediaReadiness === 'MEDIA_PENDING' || p.honestProductionStatus === 'MEDIA_PENDING'
  ).length;

  const isSourceStale = Boolean(
    project.sourceRevision &&
      project.screenplayRevision &&
      project.sourceRevision > project.screenplayRevision
  );

  const issues: string[] = [];

  if (isSourceStale) {
    issues.push(
      `CRITICAL: Upstream story source (Rev ${project.sourceRevision}) was updated after screenplay adaptation (Rev ${project.screenplayRevision}). Re-adaptation recommended.`
    );
  }

  if (runtimeDiscrepancySeconds > 4) {
    issues.push(
      `RUNTIME MISMATCH: Planned shot runtime (${totalPlannedRuntime}s) deviates from project target (${targetRuntime}s) by ${runtimeDiscrepancySeconds}s.`
    );
  }

  if (unmappedSpeechLines > 0) {
    issues.push(
      `UNMAPPED SPEECH: ${unmappedSpeechLines} screenplay dialogue line(s) are not assigned to any video shot.`
    );
  }

  if (missingMediaCount > 0) {
    issues.push(
      `MEDIA PENDING: ${missingMediaCount} Google Flow shot package(s) require approved reference image or keyframe uploads before video generation.`
    );
  }

  return {
    totalPlannedRuntime,
    targetRuntime,
    runtimeDiscrepancySeconds,
    totalShots: shots.length,
    totalScenes: scenes.length,
    ingredientsShotsCount,
    framesShotsCount,
    speechLinesCount: totalAssignedSpeechLines,
    missingSpeechCount: unmappedSpeechLines,
    missingMediaCount,
    isSourceStale,
    issues,
  };
}

/**
 * 1. Production Bible Markdown Generator
 */
export function generateProductionBibleMarkdown(project: Project): string {
  const s = project.settings;
  const v = project.visualStyle;
  const scenes = project.stage3?.scenes || [];
  const shots = project.stage3?.shots || [];
  const packages = project.stage4?.shotPackages || [];
  const assets = project.stage2?.assets || [];
  const bible = project.stage2?.styleBible;
  const audit = compileUniversalAuditReport(project);

  let md = `# ${project.title.toUpperCase()} — FILM PRODUCTION BIBLE\n`;
  md += `*Generated by XEMACS7 AI Film Studio 3.0 on ${new Date().toISOString()}*\n\n`;

  // Audit Report Section
  md += `## 0. PRODUCTION AUDIT & READINESS REPORT\n`;
  md += `- **Editorial Runtime:** ${audit.totalPlannedRuntime}s planned / ${audit.targetRuntime}s target (Discrepancy: ${audit.runtimeDiscrepancySeconds}s)\n`;
  md += `- **Shots Breakdown:** ${audit.totalShots} total shots (${audit.ingredientsShotsCount} INGREDIENTS, ${audit.framesShotsCount} FRAMES)\n`;
  md += `- **Dialogue Lines:** ${audit.speechLinesCount} assigned in screenplay (${audit.missingSpeechCount} unmapped)\n`;
  md += `- **Media Status:** ${audit.missingMediaCount === 0 ? 'ALL IMAGES AVAILABLE' : `${audit.missingMediaCount} SHOTS REQUIRE MEDIA`}\n`;
  md += `- **Source Status:** ${audit.isSourceStale ? 'SOURCE_STALE (Needs Re-Adaptation)' : 'SYNCHRONIZED'}\n`;

  if (audit.issues.length > 0) {
    md += `\n### Objective Audit Warnings:\n`;
    audit.issues.forEach((iss) => {
      md += `- ⚠️ ${iss}\n`;
    });
  }
  md += `\n---\n\n`;

  // Specifications
  md += `## 1. PROJECT SPECIFICATIONS\n`;
  md += `- **Title:** ${project.title}\n`;
  md += `- **Format:** ${s.format} (${s.aspectRatio || '16:9'})\n`;
  md += `- **Target Runtime:** ~${s.targetRuntimeSeconds} seconds\n`;
  md += `- **Platform:** ${s.platform}\n`;
  md += `- **Genres:** ${(s.genres || []).join(', ')}\n`;
  md += `- **Tone:** ${s.tone}\n`;
  md += `- **Language:** ${s.language}\n`;
  md += `- **Starting Workflow Mode:** ${project.storySourceMode}\n`;
  md += `- **Master Visual Style:** ${v.name} (${v.medium}, ${v.category})\n`;
  md += `- **Color Intent:** ${v.colorIntent}\n`;
  md += `- **Lighting Intent:** ${v.lightingIntent}\n\n`;

  // Narrative Foundation
  if (project.storyFoundation) {
    md += `## 2. PHASE 1: NARRATIVE ARCHITECTURE & CANON\n`;
    md += `**Logline:** ${project.storyFoundation.logline}\n\n`;
    md += `**Premise:** ${project.storyFoundation.premise}\n\n`;
    md += `**Protagonist:** ${project.storyFoundation.protagonist}\n\n`;
    md += `**Main Conflict:** ${project.storyFoundation.mainConflict}\n\n`;
    md += `**Emotional Stakes:** ${project.storyFoundation.emotionalStakes}\n\n`;
  }

  // Visual Reference Assets & Style Bible
  md += `## 3. PHASE 2: VISUAL STYLE BIBLE & REFERENCE PROMPTS\n`;
  if (bible) {
    md += `### Style Bible Directives:\n`;
    md += `- **Art Direction:** ${bible.artDirection || v?.description || 'Default cinematic direction'}\n`;
    md += `- **Lighting Rules:** ${bible.lightingRules}\n`;
    md += `- **Textures & Medium:** ${bible.textureAndRenderingLanguage}\n\n`;
  } else if (v) {
    md += `### Style Bible Directives:\n`;
    md += `- **Master Style:** ${v.name} (${v.medium}, ${v.category})\n`;
    md += `- **Art Direction:** ${v.description}\n`;
    md += `- **Lighting Intent:** ${v.lightingIntent}\n`;
    md += `- **Color Intent:** ${v.colorIntent}\n\n`;
  }

  if (assets.length > 0) {
    assets.forEach((a, i) => {
      md += `### Asset ${i + 1}: [${a.id}] ${a.name} (${a.type})\n`;
      md += `- **Role:** ${a.storyFunction}\n`;
      md += `- **Importance:** ${a.importance}\n`;
      md += `- **Image Media Status:** ${a.optionalReferenceImageData || a.referenceMedia?.dataUrl ? 'AVAILABLE' : 'IMAGE PENDING'}\n`;
      md += `**Master Visual Prompt (Midjourney / Flux / External):**\n\`\`\`\n${a.referencePrompt}\n\`\`\`\n\n`;
    });
  } else {
    md += `*No individual asset prompt overrides registered. Project inherits master visual style directives.*\n\n`;
  }

  // Screenplay
  if (scenes.length > 0) {
    md += `## 4. PHASE 1: SCREENPLAY SCENES\n`;
    scenes.forEach((sc) => {
      md += `### SCENE ${sc.sceneNumber}: ${sc.slugline || sc.title} (~${sc.estimatedSceneDuration}s)\n`;
      md += `**Story Purpose:** ${sc.storyPurpose}\n`;
      md += `**Location:** ${sc.locationId} | **Time:** ${sc.timeOfDay}\n`;
      md += `**Characters Present:** ${(sc.characterIds || []).join(', ')}\n\n`;
      md += `**Script / Action:**\n\`\`\`\n${sc.scriptText || sc.storyPurpose}\n\`\`\`\n\n`;

      if (sc.dialogueBlocks && sc.dialogueBlocks.length > 0) {
        md += `**Spoken Dialogue / VO:**\n`;
        sc.dialogueBlocks.forEach((d) => {
          md += `- **${d.speakerName}** (${d.type}): "${d.dialogue}"\n`;
        });
        md += `\n`;
      }
    });
  }

  // Google Flow Production Packages
  if (packages.length > 0 || shots.length > 0) {
    md += `## 5. PHASE 3: GOOGLE FLOW MASTER PRODUCTION PACKAGES\n`;
    const items = packages.length > 0 ? packages : (shots as any);

    items.forEach((item: any) => {
      const isPkg = Boolean(item.videoPrompt);
      const shotId = item.shotId;
      const duration = item.plannedDuration || item.duration || 8;
      const flowMode = item.flowMode;
      const targetModel = item.targetModel || 'Google Veo 2 / Flow Standard';

      md += `### Shot [${shotId}] (${duration}s, Route: ${flowMode})\n`;
      md += `- **Target Model:** ${targetModel}\n`;
      md += `- **Readiness Status:** ${item.honestProductionStatus || item.mediaReadiness || 'TEXT_READY'}\n`;

      if (item.continuationFromShotId) {
        md += `- **Continuation:** Genuine visual continuation from Shot [${item.continuationFromShotId}]\n`;
        md += `- **Continuation Reason:** ${item.continuationJustification || 'Continuous motion & staging'}\n`;
      }

      if (isPkg && item.videoPrompt) {
        md += `\n**Google Flow Video Prompt:**\n\`\`\`\n${item.videoPrompt}\n\`\`\`\n`;
      }

      // Spoken Dialogue
      if (item.audioLanes?.dialogue && item.audioLanes.dialogue !== 'None') {
        md += `- **Dialogue:** ${item.audioLanes.dialogue}\n`;
      } else if (item.dialogueText) {
        md += `- **Dialogue:** ${item.dialogueText}\n`;
      } else {
        md += `- **Dialogue:** Intentionally Silent / No dialogue\n`;
      }

      // Reference Attachments Checklist
      const checklist = item.referenceChecklist || [];
      if (checklist.length > 0) {
        md += `- **Image Reference Attachments:**\n`;
        checklist.forEach((c: any) => {
          md += `  * [${c.assetId}] ${c.assetName} (${c.assetType}) — Status: ${c.mediaStatus} (${c.notes || 'Flow Slot'})\n`;
        });
      }

      md += `\n`;
    });
  }

  return md;
}

/**
 * 2. Google Flow Manifest JSON Generator
 */
export function generateFlowManifestJson(project: Project): string {
  const audit = compileUniversalAuditReport(project);
  const packages = project.stage4?.shotPackages || [];
  const scenes = project.stage3?.scenes || [];
  const shots = project.stage3?.shots || [];

  const manifest = {
    studioVersion: '3.0',
    exportedAt: new Date().toISOString(),
    project: {
      id: project.projectId,
      title: project.title,
      format: project.settings.format,
      aspectRatio: project.settings.aspectRatio,
      targetRuntimeSeconds: project.settings.targetRuntimeSeconds,
      platform: project.settings.platform,
      genres: project.settings.genres,
      visualStyle: {
        id: project.visualStyle.presetId,
        name: project.visualStyle.name,
        medium: project.visualStyle.medium,
      },
    },
    auditReport: audit,
    scenes: scenes.map((sc) => ({
      sceneId: sc.sceneId,
      sceneNumber: sc.sceneNumber,
      title: sc.title,
      slugline: sc.slugline,
      estimatedDuration: sc.estimatedSceneDuration,
      dialogueCount: sc.dialogueBlocks?.length || 0,
      dialogueBlocks: sc.dialogueBlocks || [],
    })),
    productionShots: packages.map((pkg) => ({
      shotId: pkg.shotId,
      sceneId: pkg.sceneId,
      order: pkg.order,
      plannedDuration: pkg.plannedDuration,
      flowMode: pkg.flowMode,
      targetModel: pkg.targetModel,
      honestStatus: pkg.honestProductionStatus || pkg.mediaReadiness,
      continuationFromShotId: pkg.continuationFromShotId || null,
      continuationJustification: pkg.continuationJustification || null,
      videoPrompt: pkg.videoPrompt,
      speech: {
        dialogue: pkg.audioLanes?.dialogue || 'None',
        narration: pkg.audioLanes?.narrationOrVO || 'None',
        lipSyncRequired: pkg.audioLanes?.lipSyncRequired || false,
      },
      audioLanes: pkg.audioLanes,
      referenceAttachments: (pkg.referenceChecklist || []).map((c) => ({
        assetId: c.assetId,
        assetType: c.assetType,
        assetName: c.assetName,
        role: c.role,
        mediaStatus: c.mediaStatus,
        prompt: c.referencePromptText,
        instruction: c.notes,
      })),
      timingBeats: pkg.actionTiming,
      continuityAnchors: pkg.continuityAnchors,
      negativeExclusions: pkg.exclusions,
    })),
  };

  return JSON.stringify(manifest, null, 2);
}

/**
 * 3. Cinematic Shot List CSV Generator
 */
export function generateShotListCsv(project: Project): string {
  const shots = project.stage3?.shots || [];
  const packages = project.stage4?.shotPackages || [];

  const headers = [
    'Shot ID',
    'Order',
    'Scene ID',
    'Duration (s)',
    'Route (Flow Mode)',
    'Continuation From Shot',
    'Shot Size',
    'Camera Movement',
    'Lens Intent',
    'Characters',
    'Location',
    'Dialogue / Speech',
    'Media Status',
    'Google Flow Video Prompt',
  ];

  const escapeCsv = (str?: string | null) => {
    if (!str) return '""';
    const clean = String(str).replace(/"/g, '""');
    return `"${clean}"`;
  };

  const rows = shots.map((sh) => {
    const pkg = packages.find((p) => p.shotId === sh.shotId);
    const speech = pkg?.audioLanes?.dialogue && pkg.audioLanes.dialogue !== 'None'
      ? pkg.audioLanes.dialogue
      : sh.dialogueText || 'None';
    const prompt = pkg?.videoPrompt || sh.blockingAndMovement || '';
    const status = pkg?.honestProductionStatus || pkg?.mediaReadiness || 'TEXT_READY';

    return [
      escapeCsv(sh.shotId),
      sh.order,
      escapeCsv(sh.sceneId),
      sh.duration,
      escapeCsv(sh.flowMode),
      escapeCsv(sh.continuationFromShotId || 'None (Independent)'),
      escapeCsv(sh.shotSize),
      escapeCsv(sh.cameraMovement),
      escapeCsv(sh.lensIntent || '35mm anamorphic'),
      escapeCsv((sh.characterIds || []).join(', ')),
      escapeCsv(sh.locationId),
      escapeCsv(speech),
      escapeCsv(status),
      escapeCsv(prompt),
    ].join(',');
  });

  return [headers.join(','), ...rows].join('\n');
}

/**
 * 4. Universal Single Authoritative Export Package
 */
export function generateUniversalExportPackage(project: Project): AuthoritativeExportPackage {
  const auditSummary = compileUniversalAuditReport(project);
  const productionBibleMarkdown = generateProductionBibleMarkdown(project);
  const flowManifestJson = generateFlowManifestJson(project);
  const shotListCsv = generateShotListCsv(project);
  const projectBackupJson = JSON.stringify(project, null, 2);

  return {
    productionBibleMarkdown,
    flowManifestJson,
    shotListCsv,
    projectBackupJson,
    auditSummary,
  };
}
